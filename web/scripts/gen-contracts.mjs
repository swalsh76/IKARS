// Generates the terminal's API types and validators from the engine's JSON Schema (PLAN D3 as
// amended): src/api/contracts.ts (the types) and src/api/validators.js (ajv's standalone code, so
// the page never compiles code at run time and the CSP's "no eval" holds). Every object refuses
// unknown fields: the engine serves its own terminal, so the two always match, and drift fails
// loudly. With --check, nothing is written and a difference from the committed files fails.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv from "ajv";
import standaloneCode from "ajv/dist/standalone/index.js";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const schema = JSON.parse(readFileSync(join(root, "..", "contracts", "ikars-api.schema.json"), "utf8"));
const defs = schema.$defs;
const names = Object.keys(defs).sort();

// unknown fields refused everywhere an object lists its fields
for (const def of Object.values(defs)) {
  if (def.type === "object" && def.properties && def.additionalProperties === undefined) {
    def.additionalProperties = false;
  }
}

const header = "// Generated by scripts/gen-contracts.mjs from contracts/ikars-api.schema.json: do not edit.\n";

async function types() {
  const all = {
    title: "Contracts",
    type: "object",
    properties: Object.fromEntries(names.map((n) => [n, { $ref: `#/$defs/${n}` }])),
    required: names,
    additionalProperties: false,
    $defs: defs,
  };
  const body = await compile(all, "Contracts", {
    bannerComment: "",
    unknownAny: true,
    format: false,
    style: { singleQuote: false },
  });
  const events = Object.entries(schema.stream_events)
    .map(([event, kind]) => `  ${event}: "${kind}",`)
    .join("\n");
  return (
    header +
    `\nexport const API_VERSION = "${schema.version}";\n\n` +
    body.trim() +
    `\n\n/** The stream's event names and the contract each carries. */\nexport const STREAM_EVENTS = {\n${events}\n} as const;\n` +
    `\nexport type ContractName = keyof Contracts;\nexport type StreamEvent = keyof typeof STREAM_EVENTS;\n`
  );
}

function validators() {
  // inlineRefs off: each referenced contract is one shared function, not a copy in every validator
  const ajv = new Ajv({ code: { source: true, esm: true }, strict: false, inlineRefs: false });
  ajv.addSchema({ $id: "ikars", $defs: defs });
  const map = Object.fromEntries(names.map((n) => [n, `ikars#/$defs/${n}`]));
  return "/* eslint-disable */\n" + header + standaloneCode(ajv, map) + "\n";
}

const declarations =
  header +
  "\nexport interface Validator {\n  (data: unknown): boolean;\n  errors?: { instancePath: string; message?: string }[] | null;\n}\n\n" +
  names.map((n) => `export declare const ${n}: Validator;`).join("\n") +
  "\n";

const outputs = {
  [join(root, "src", "api", "contracts.ts")]: await types(),
  [join(root, "src", "api", "validators.js")]: validators(),
  [join(root, "src", "api", "validators.d.ts")]: declarations,
};

const check = process.argv.includes("--check");
let stale = 0;
for (const [path, text] of Object.entries(outputs)) {
  if (check) {
    let committed = "";
    try {
      committed = readFileSync(path, "utf8");
    } catch {
      // missing counts as stale
    }
    if (committed !== text) {
      console.error(`out of date: ${path} (run: pnpm gen)`);
      stale += 1;
    }
  } else {
    writeFileSync(path, text);
  }
}
if (stale) process.exit(1);
console.log(check ? "contracts: generated files are current" : `contracts: wrote ${Object.keys(outputs).length} files`);
